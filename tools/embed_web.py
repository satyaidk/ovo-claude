#!/usr/bin/env python3
"""Embed web/index.html into the firmware as a gzipped byte array.

Why: the ESP32 serves the controller page straight from flash. Gzipping it
shrinks the page to roughly a quarter of its size, which saves flash and makes
the page load faster over Wi-Fi; every browser unpacks it transparently
because the firmware sends `Content-Encoding: gzip`.

Usage (from the repository root):
    python tools/embed_web.py           # regenerate firmware/MochiEyes/src/web/WebUi.h
    python tools/embed_web.py --check   # exit 1 if WebUi.h is out of date (CI)

Edit web/index.html, never the generated WebUi.h.

Line endings are normalised to LF before embedding, so a Windows checkout
(CRLF) and the Linux CI checkout produce and accept the same page.
"""
import argparse
import gzip
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "index.html"
OUT = ROOT / "firmware" / "MochiEyes" / "src" / "web" / "WebUi.h"

HEADER = """\
// Generated by tools/embed_web.py from web/index.html - do not edit.
// The controller page, gzipped ({raw} -> {packed} bytes).
#pragma once
#include <stddef.h>
#include <stdint.h>
#include <pgmspace.h>

static const size_t INDEX_HTML_RAW_LEN = {raw};
static const size_t INDEX_HTML_GZ_LEN = {packed};
static const uint8_t INDEX_HTML_GZ[] PROGMEM = {{
{body}
}};
"""


def source_bytes() -> bytes:
    """web/index.html with LF line endings, whatever the checkout uses."""
    return SRC.read_bytes().replace(b"\r\n", b"\n")


def build() -> str:
    raw = source_bytes()
    packed = gzip.compress(raw, compresslevel=9, mtime=0)  # mtime=0: same input, same bytes
    lines = []
    for i in range(0, len(packed), 20):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in packed[i:i + 20]) + ",")
    return HEADER.format(raw=len(raw), packed=len(packed), body="\n".join(lines))


def embedded_html() -> bytes:
    """Decompress the bytes currently stored in WebUi.h."""
    text = OUT.read_text(encoding="utf-8")
    body = text.split("PROGMEM = {", 1)[1].rsplit("};", 1)[0]
    data = bytes(int(h, 16) for h in re.findall(r"0x([0-9a-f]{2})", body))
    return gzip.decompress(data)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify WebUi.h matches web/index.html")
    args = ap.parse_args()

    if args.check:
        # Compare decompressed content, not bytes: zlib versions may pack differently.
        if not OUT.exists() or embedded_html().replace(b"\r\n", b"\n") != source_bytes():
            print("WebUi.h is out of date: run python tools/embed_web.py", file=sys.stderr)
            return 1
        print("WebUi.h is up to date")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    raw = source_bytes()
    print(f"wrote {OUT.relative_to(ROOT)}: {len(raw)} bytes -> {len(gzip.compress(raw, 9, mtime=0))} bytes gzipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
